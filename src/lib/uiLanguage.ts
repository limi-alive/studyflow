let current: UiLanguage = (() => {
  if (typeof window === 'undefined') return 'fa';
  try { return window.localStorage.getItem('studyflow.uiLanguage') === 'en' ? 'en' : 'fa'; }
  catch { return 'fa'; }
})();
const listeners = new Set<() => void>();
export function getUiLanguage(): UiLanguage { return current; }
export function setUiLanguage(next: UiLanguage) {
  // Re-apply document direction even when the saved setting already matches.
  // index.html starts with a neutral English bootstrap until user settings load.
  if (typeof document !== 'undefined') { document.documentElement.lang=next; document.documentElement.dir=next==='fa'?'rtl':'ltr'; }
  if (next === current) return;
  current = next;
  if (typeof window !== 'undefined') try { localStorage.setItem('studyflow.uiLanguage',next); } catch { /* private browsing */ }
  listeners.forEach(listener=>listener());
}
const subscribe = (listener:()=>void) => { listeners.add(listener);return ()=>{listeners.delete(listener);}; };
export function useUiLanguage() { return useSyncExternalStore(subscribe,getUiLanguage,()=> 'fa' as UiLanguage); }
export function translateUi(label: string, language: UiLanguage) {
  const raw=label.trim();
  if (language==='fa') return englishToPersian[raw] ?? raw;
  return persianToEnglish[raw] ?? raw;
}
export function useUiText() {
  const language=useUiLanguage();
  return (label:string) => translateUi(label, language);
}
export function formatUiNumber(value:number) {
  return new Intl.NumberFormat(current==='fa'?'fa-IR':'en-US').format(value);
}
